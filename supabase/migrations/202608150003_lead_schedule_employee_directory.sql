insert into rt_directory_resolution
select
  department.id as department_id,
  seed.*,
  matches.staff_ids,
  coalesce(pg_catalog.cardinality(matches.staff_ids), 0) as match_count
from public.departments department
cross join rt_directory_seed seed
left join lateral (
  select pg_catalog.array_agg(profile.id order by profile.id) as staff_ids
  from public.staff_profiles profile
  where profile.department_id = department.id
    and public.normalize_staff_directory_name(profile.display_name) = any (
      select public.normalize_staff_directory_name(candidate.name)
      from pg_catalog.unnest(
        array[seed.first_name || ' ' || seed.last_name] || seed.aliases
      ) as candidate(name)
    )
) matches on true;

insert into public.staff_directory_seed_conflicts (
  department_id,
  staff_profile_id,
  seed_display_name,
  field_name,
  existing_value,
  incoming_value,
  source_migration
)
select
  resolution.department_id,
  resolution.staff_ids[1],
  resolution.first_name || ' ' || resolution.last_name,
  conflict.field_name,
  conflict.existing_value,
  conflict.incoming_value,
  '202608150003_lead_schedule_employee_directory'
from rt_directory_resolution resolution
join public.staff_profiles profile on profile.id = resolution.staff_ids[1]
cross join lateral (
  values
    ('first_name', profile.first_name, resolution.first_name),
    ('last_name', profile.last_name, resolution.last_name),
    ('hire_date', profile.hire_date::text, resolution.hire_date::text),
    ('phone_number', profile.phone_number, resolution.phone_number),
    ('employment_type', profile.employment_type::text, resolution.employment_type::text),
    ('directory_shift', profile.directory_shift::text, resolution.directory_shift::text)
) as conflict(field_name, existing_value, incoming_value)
where resolution.match_count = 1
  and conflict.existing_value is not null
  and conflict.existing_value <> conflict.incoming_value
on conflict do nothing;

update public.staff_profiles profile
set
  first_name = coalesce(profile.first_name, resolution.first_name),
  last_name = coalesce(profile.last_name, resolution.last_name),
  hire_date = coalesce(profile.hire_date, resolution.hire_date),
  phone_number = coalesce(profile.phone_number, resolution.phone_number),
  employment_type = case
    when resolution.first_name = 'Renae' and resolution.last_name = 'Waldschmidt'
      then resolution.employment_type
    else profile.employment_type
  end,
  directory_shift = coalesce(profile.directory_shift, resolution.directory_shift),
  name_aliases = array(
    select distinct alias_value
    from pg_catalog.unnest(
      profile.name_aliases || resolution.aliases
    ) as alias_value
    where pg_catalog.btrim(alias_value) <> ''
    order by alias_value
  )
from rt_directory_resolution resolution
where resolution.match_count = 1
  and profile.id = resolution.staff_ids[1];

