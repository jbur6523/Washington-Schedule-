create or replace function public.normalize_staff_directory_name(value text)
returns text
language plpgsql
immutable
set search_path = pg_catalog
as $$
declare
  cleaned text;
  comma_parts text[];
begin
  cleaned := pg_catalog.btrim(coalesce(value, ''));
  if pg_catalog.strpos(cleaned, ',') > 0 then
    comma_parts := pg_catalog.string_to_array(cleaned, ',');
    if pg_catalog.cardinality(comma_parts) = 2 then
      cleaned := pg_catalog.btrim(comma_parts[2]) || ' ' || pg_catalog.btrim(comma_parts[1]);
    end if;
  end if;

  return pg_catalog.regexp_replace(
    pg_catalog.lower(pg_catalog.regexp_replace(cleaned, '[^[:alnum:]]+', ' ', 'g')),
    '\s+',
    ' ',
    'g'
  );
end;
$$;

revoke all on function public.normalize_staff_directory_name(text) from public;

