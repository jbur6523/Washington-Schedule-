create temporary table rt_directory_resolution on commit drop as
select
  department.id as department_id,
  seed.*,
  matches.staff_ids,
  coalesce(pg_catalog.cardinality(matches.staff_ids), 0) as match_count
from public.departments department
cross join rt_directory_seed seed
left join lateral (
  select pg_catalog.array_agg(profile.id order by profile.id) as staff_ids
  from public.staff_profiles profile
  where profile.department_id = department.id
    and public.normalize_staff_directory_name(profile.display_name) = any (
      select public.normalize_staff_directory_name(candidate.name)
      from pg_catalog.unnest(
        array[seed.first_name || ' ' || seed.last_name] || seed.aliases
      ) as candidate(name)
    )
) matches on true;

insert into public.staff_directory_seed_conflicts (
  department_id,
  staff_profile_id,
  seed_display_name,
  field_name,
  existing_value,
  incoming_value,
  source_migration
)
select
  resolution.department_id,
  null,
  resolution.first_name || ' ' || resolution.last_name,
  'identity',
  pg_catalog.array_to_string(resolution.staff_ids, ', '),
  'Exactly one existing staff profile',
  '202608150003_lead_schedule_employee_directory'
from rt_directory_resolution resolution
where resolution.match_count > 1
on conflict do nothing;

with insert_candidates as (
  select
    resolution.*,
    public.generated_staff_username_base(resolution.first_name || ' ' || resolution.last_name) as base_username,
    row_number() over (
      partition by public.generated_staff_username_base(resolution.first_name || ' ' || resolution.last_name)
      order by resolution.department_id, resolution.last_name, resolution.first_name
    ) as username_rank
  from rt_directory_resolution resolution
  where resolution.match_count = 0
), resolved_usernames as (
  select
    candidate.*,
    available.username
  from insert_candidates candidate
  cross join lateral (
    select username_option.username
    from (
      select
        sequence.value,
        case
          when sequence.value = 0 then candidate.base_username
          else candidate.base_username || (sequence.value + 1)::text
        end as username
      from pg_catalog.generate_series(0, 999) as sequence(value)
    ) username_option
    where not exists (
      select 1
      from public.staff_profiles existing
      where existing.username_normalized = public.normalize_username(username_option.username)
    )
    order by username_option.value
    offset (candidate.username_rank - 1)
    limit 1
  ) available
)
